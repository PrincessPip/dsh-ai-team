param([switch]$Write)

# review-index.ps1 - build a queryable index of every review verdict
#
# PURPOSE: turn decisions/*.json into one table + a rework/verdict statistics
#          block, so "which units needed how many rounds" and "how often does
#          the reviewer catch something" stop living in my memory.
# WHY: P2 = decision log + rework stats. A log you cannot count is a folder.
#
# SCOPE: reads decisions/*.json only. "-raw.txt" files are re-exports of the
#        same verdicts and are excluded on purpose (double counting).
#        Files recovered from raw text by review-backfill.ps1 are ordinary
#        .json here; the provenance list lives in decisions/BACKFILL.md.
#
# USAGE: powershell -NoProfile -File scripts/review-index.ps1          (print)
#        powershell -NoProfile -File scripts/review-index.ps1 -Write   (write decisions/INDEX.md)
# EXIT:  0 = ok | 1 = a verdict file failed to parse
#
# ASCII-only on purpose: Windows PowerShell 5.1 decodes a BOM-less file as
# code page 936 and would mangle non-ASCII text.

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$dir = Join-Path $root 'decisions'
$utf8 = New-Object System.Text.UTF8Encoding($false)

$rows = New-Object System.Collections.ArrayList
$bad = 0

foreach ($f in (Get-ChildItem -LiteralPath $dir -Filter '*.json' -File | Sort-Object Name)) {
    $name = $f.BaseName
    $round = 1
    $unit = $name
    $m = [regex]::Match($name, '^(?<id>.+?)-round(?<n>\d+)$')
    if ($m.Success) {
        $unit = $m.Groups['id'].Value
        $round = [int]$m.Groups['n'].Value
    }

    try {
        $j = [System.IO.File]::ReadAllText($f.FullName, $utf8) | ConvertFrom-Json
    } catch {
        Write-Output ("[FAIL] {0}: {1}" -f $f.Name, $_.Exception.Message)
        $bad++
        continue
    }

    $crit = @($j.criteria)
    $fails = @($crit | Where-Object { $_.status -eq 'fail' } | ForEach-Object { $_.id })
    $unsure = @($crit | Where-Object { $_.status -eq 'unverified' } | ForEach-Object { $_.id })

    [void]$rows.Add([pscustomobject]@{
        Unit      = $unit
        Round     = $round
        File      = $f.Name
        Verdict   = [string]$j.verdict
        Conf      = [double]$j.confidence
        Criteria  = $crit.Count
        Blocking  = @($j.blocking).Count
        NonBlock  = @($j.nonblocking).Count
        FailIds   = ($fails -join ',')
        UnsureIds = ($unsure -join ',')
    })
}

if ($rows.Count -eq 0) {
    Write-Output "RESULT=NO_VERDICTS"
    exit 0
}

$sorted = @($rows | Sort-Object Unit, Round)

# ---- statistics -----------------------------------------------------------
$total     = $sorted.Count
$passN     = @($sorted | Where-Object { $_.Verdict -eq 'pass' }).Count
$reworkN   = @($sorted | Where-Object { $_.Verdict -eq 'rework' }).Count
$escalN    = @($sorted | Where-Object { $_.Verdict -eq 'escalate' }).Count
$meanConf  = [math]::Round((($sorted | Measure-Object -Property Conf -Average).Average), 3)
$blockSum  = ($sorted | Measure-Object -Property Blocking -Sum).Sum
$nonBlockSum = ($sorted | Measure-Object -Property NonBlock -Sum).Sum

$units = @($sorted | Group-Object Unit | ForEach-Object {
    # @() is load-bearing: in PS 5.1 a single-item pipeline result is a scalar
    # and .Count does not exist on it, which silently produced empty "Rounds".
    $g = @($_.Group | Sort-Object Round)
    [pscustomobject]@{
        Unit      = $_.Name
        Rounds    = $g.Count
        Last      = $g[-1].Verdict
        Verdicts  = (($g | ForEach-Object { $_.Verdict }) -join ' > ')
        Blocking  = ($g | Measure-Object -Property Blocking -Sum).Sum
    }
} | Sort-Object Unit)

$unitCount      = $units.Count
$firstPassUnits = @($units | Where-Object { $_.Rounds -eq 1 -and $_.Last -eq 'pass' }).Count
$multiRound     = @($units | Where-Object { $_.Rounds -gt 1 } | Sort-Object Rounds -Descending)

# ---- render ---------------------------------------------------------------
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('# Review index (generated)')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('> Generated by `powershell -NoProfile -File scripts/review-index.ps1 -Write`. **Do not edit by hand.**')
[void]$sb.AppendLine('> Source: `decisions/*.json` (`*-raw.txt` excluded to avoid double counting).')
[void]$sb.AppendLine('> Files recovered from raw text are listed in `decisions/BACKFILL.md`.')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('## Rounds')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('| Unit | Round | Verdict | Conf | Criteria | Blocking | Non-blocking | Failed / unverified |')
[void]$sb.AppendLine('|---|---|---|---|---|---|---|---|')
foreach ($r in $sorted) {
    $fu = @()
    if ($r.FailIds)   { $fu += ('fail: ' + $r.FailIds) }
    if ($r.UnsureIds) { $fu += ('unverified: ' + $r.UnsureIds) }
    [void]$sb.AppendLine(('| `{0}` | {1} | **{2}** | {3} | {4} | {5} | {6} | {7} |' -f `
        $r.Unit, $r.Round, $r.Verdict, $r.Conf, $r.Criteria, $r.Blocking, $r.NonBlock, ($fu -join '; ')))
}
[void]$sb.AppendLine('')
[void]$sb.AppendLine('## Summary')
[void]$sb.AppendLine('')
[void]$sb.AppendLine(('- verdicts: **{0}** rounds ---- pass {1} / rework {2} / escalate {3}' -f $total, $passN, $reworkN, $escalN))
[void]$sb.AppendLine(('- delivery units: **{0}**; passed on round 1: **{1}/{0}**' -f $unitCount, $firstPassUnits))
[void]$sb.AppendLine(('- mean confidence: **{0}**' -f $meanConf))
[void]$sb.AppendLine(('- blocking total: **{0}**; non-blocking total: **{1}**' -f $blockSum, $nonBlockSum))
[void]$sb.AppendLine('')
[void]$sb.AppendLine('## Units by round count')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('| Unit | Rounds | Verdict chain | Blocking total |')
[void]$sb.AppendLine('|---|---|---|---|')
foreach ($u in ($units | Sort-Object @{ Expression = 'Rounds'; Descending = $true }, Unit)) {
    [void]$sb.AppendLine(('| `{0}` | {1} | {2} | {3} |' -f $u.Unit, $u.Rounds, $u.Verdicts, $u.Blocking))
}
[void]$sb.AppendLine('')
[void]$sb.AppendLine('> Reading: `rework` = fixable inside the current design; `escalate` = the reviewer needs a human')
[void]$sb.AppendLine('> or cannot verify; `pass` = delivered. A unit that never leaves `rework`/`escalate` is a design smell,')
[void]$sb.AppendLine('> not a worker skill problem.')

$out = $sb.ToString()

if ($Write) {
    $target = Join-Path $dir 'INDEX.md'
    [System.IO.File]::WriteAllText($target, $out, $utf8)
    Write-Output ("wrote {0} ({1} bytes)" -f $target, (Get-Item -LiteralPath $target).Length)
} else {
    Write-Output $out
}

Write-Output ("RESULT=OK rounds={0} units={1} pass={2} rework={3} escalate={4} parse_failures={5}" -f `
    $total, $unitCount, $passN, $reworkN, $escalN, $bad)

if ($bad -gt 0) { exit 1 }
exit 0
